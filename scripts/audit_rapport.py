def main():
    doc = TocDocTemplate(
        OUT, pagesize=A4,
        leftMargin=MARGIN, rightMargin=MARGIN, topMargin=66, bottomMargin=62,
        title=DOC_TITLE, author="Z.ai", creator="Z.ai",
        subject="Audit hostile interne du projet Légalement Subjective",
    )

    toc = TableOfContents()
    toc.levelStyles = [S["toc0"]]

    story = []
    story.append(Paragraph("<b>Sommaire</b>", S["toctitle"]))
    story.append(HRFlowable(width="100%", thickness=1.2, color=ACCENT,
                            spaceBefore=0, spaceAfter=14))
    story.append(toc)
    story.append(PageBreak())
    story.append(BodyStartMarker())
    story += render(CH_1_4)
    story += render(CH_5_8)

    doc.multiBuild(story, onFirstPage=draw_chrome, onLaterPages=draw_chrome)
    print("BODY OK:", OUT, os.path.getsize(OUT), "octets")


if __name__ == "__main__":
    main()

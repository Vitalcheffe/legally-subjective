def typo_fr(text):
    """Typographie francaise : tiret cadratin lie par espaces inseparables
    (jamais de tiret en debut de ligne dans une phrase)."""
    return text.replace(" — ", "\u00a0— ")


def render(blocks):
    story = []
    pending_h = None  # (heading elements) a coller au premier bloc suivant
    for blk in blocks:
        kind = blk[0]
        if kind in ("h1", "h2", "h3"):
            if pending_h is not None:
                # un titre suit un titre non encore rattaché : on le verse
                # direct (sinon il est ecrase et disparait du document)
                story += pending_h
        if kind == "h1":
            pending_h = h1_block(blk[1])
            continue
        if kind == "h2":
            pending_h = [CondPageBreak(90),
                         Paragraph("<b>%s</b>" % blk[1], S["h2"])]
            continue
        if kind == "h3":
            pending_h = [CondPageBreak(70),
                         Paragraph("<b>%s</b>" % blk[1], S["h3"])]
            continue

        if kind == "p":
            el = [Paragraph(typo_fr(blk[1]), S["body"])]
        elif kind == "bullets":
            el = [Paragraph("•  " + typo_fr(it), S["item"]) for it in blk[1]]
        elif kind == "nums":
            el = [Paragraph("<b>%d.</b>  %s" % (i + 1, typo_fr(it)), S["item"])
                  for i, it in enumerate(blk[1])]
        elif kind == "quote":
            el = make_quote(blk[1], blk[2])
        elif kind == "callout":
            el = make_callout(blk[1][0], blk[1][1])
        elif kind == "statrow":
            el = make_statrow(blk[1])
        elif kind == "table":
            el = make_table(blk[1])
        elif kind == "fig":
            img = embed_image(blk[1])
            cap = Paragraph(blk[2], S["caption"])
            el = [Spacer(1, 16)] + safe_keep_together([img, cap]) + [Spacer(1, 12)]
        elif kind == "note":
            el = make_note(blk[1])
        else:
            raise ValueError("bloc inconnu: %r" % kind)

        if pending_h is not None:
            # les titres portent leur propre CondPageBreak anti-orphelin :
            # pas de re-groupement (l'imbrication de conteneurs perd les
            # bookmarks de TOC).
            story += pending_h
            story += el
            pending_h = None
        else:
            story += el
    if pending_h is not None:
        story += pending_h
    return story



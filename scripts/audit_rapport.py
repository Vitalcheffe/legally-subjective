class BodyStartMarker(Flowable):
    """Marque la premiere page du corps (numerotation arabe)."""

    def __init__(self):
        super().__init__()
        self.width = 0
        self.height = 0

    def draw(self):
        pass


class TocDocTemplate(SimpleDocTemplate):
    """SimpleDocTemplate + alimentation de la TOC + debut du corps."""

    def __init__(self, *a, **kw):
        super().__init__(*a, **kw)
        self._body_start = None
        self._toc_seen = set()

    def beforeDocument(self):
        self._toc_seen = set()

    def afterFlowable(self, flowable):
        if isinstance(flowable, BodyStartMarker):
            self._body_start = self.page
            return
        if hasattr(flowable, "bookmark_name"):
            key = getattr(flowable, "bookmark_key", "")
            if key and key not in self._toc_seen:
                self._toc_seen.add(key)
                level = getattr(flowable, "bookmark_level", 0)
                text = getattr(flowable, "bookmark_text", "")
                # numero AFFICHE (arabe, reset apres le sommaire) pour la TOC
                bs = self._body_start
                shown = self.page - bs + 1 if (bs and self.page >= bs) else self.page
                self.notify("TOCEntry", (level, text, shown, key))


ROMAN = {1: "i", 2: "ii", 3: "iii", 4: "iv", 5: "v", 6: "vi", 7: "vii",
         8: "viii", 9: "ix", 10: "x"}


def draw_chrome(canvas, doc):
    canvas.saveState()
    # --- en-tete : titre + filet accent
    canvas.setFont("FreeSerif", 7.5)
    canvas.setFillColor(TEXT_MUTED)
    canvas.drawString(MARGIN, PAGE_H - 40, DOC_TITLE.upper())
    canvas.setStrokeColor(ACCENT)
    canvas.setLineWidth(1.2)
    canvas.line(MARGIN, PAGE_H - 47, PAGE_W - MARGIN, PAGE_H - 47)
    # --- pied de page : filet fin + auteur + numero
    canvas.setStrokeColor(BORDER)
    canvas.setLineWidth(0.5)
    canvas.line(MARGIN, 46, PAGE_W - MARGIN, 46)
    canvas.setFont("FreeSerif", 7.5)
    canvas.setFillColor(TEXT_MUTED)
    canvas.drawString(MARGIN, 34, "Instruction interne — établie au commit 3ec9f3b")
    body_start = getattr(doc, "_body_start", None)
    if body_start is None or doc.page < body_start:
        num = ROMAN.get(doc.page, str(doc.page))
    else:
        num = str(doc.page - body_start + 1)
    canvas.drawRightString(PAGE_W - MARGIN, 34, num)
    canvas.restoreState()


# ------------------------------------------------------------------ helpers
def safe_keep_together(elements):
    total = 0
    for el in elements:
        try:
            w, h = el.wrap(AVAIL_W, PAGE_H)
        except Exception:
            h = 40  # element non mesurable hors build (KeepTogether imbrique...)
        total += h
    if total <= MAX_KEEP:
        return [KeepTogether(elements)]
    if len(elements) >= 2:
        return [KeepTogether(elements[:2])] + list(elements[2:])
    return list(elements)


def add_heading(text, style, level=0):
    key = "h_" + hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph('<a name="%s"/><b>%s</b>' % (key, text), style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p


BOOKMARK_ATTRS = ("bookmark_name", "bookmark_level", "bookmark_text",
                  "bookmark_key")


def h1_block(text):
    heading = add_heading(text, S["h1"], 0)
    rule = HRFlowable(width="100%", thickness=1.2, color=ACCENT,
                      spaceBefore=0, spaceAfter=10)
    kt = KeepTogether([heading, rule])
    # le bookmark vit sur le conteneur ET sur le paragraphe : selon que le
    # KeepTogether tient entier (notify conteneur) ou se scinde (notify
    # enfants), afterFlowable verra toujours les attributs.
    for attr in BOOKMARK_ATTRS:
        setattr(kt, attr, getattr(heading, attr))
    return [CondPageBreak(AVAIL_H * 0.25), kt]


def embed_image(path, max_w=AVAIL_W, max_h=300):
    img = PILImage.open(path)
    ow, oh = img.size
    ratio = min(max_w / ow if ow > max_w else 1.0,
                max_h / oh if oh > max_h else 1.0)
    return Image(path, width=ow * ratio, height=oh * ratio)


def make_table(spec):
    head, rows = spec["head"], spec["rows"]
    ratios = spec["ratios"]
    widths = [r * AVAIL_W * 0.98 for r in ratios]
    data = [[Paragraph("<b>%s</b>" % h, S["th"]) for h in head]]
    for row in rows:
        data.append([Paragraph(typo_fr(str(c)), S["td"]) for c in row])
    t = Table(data, colWidths=widths, hAlign="CENTER", repeatRows=1)
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), HEADER_FILL),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("GRID", (0, 0), (-1, -1), 0.5, BORDER),
        ("LEFTPADDING", (0, 0), (-1, -1), 7),
        ("RIGHTPADDING", (0, 0), (-1, -1), 7),
        ("TOPPADDING", (0, 0), (-1, -1), 5.5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5.5),
    ]
    for i in range(1, len(data)):
        if i % 2 == 0:
            style.append(("BACKGROUND", (0, i), (-1, i), TABLE_STRIPE))
    t.setStyle(TableStyle(style))
    out = [Spacer(1, 12)]
    if len(rows) <= 12:
        out += safe_keep_together([t])
    else:
        out.append(t)
    out.append(Paragraph(spec["caption"], S["caption"]))
    out.append(Spacer(1, 10))
    return out


